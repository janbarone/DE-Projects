"""JSON schemas for the match payload arrays used by the Spark silver job."""
from pyspark.sql import types as T

PLAYER_SCHEMA = T.StructType([
    T.StructField("player_slot", T.IntegerType()),
    T.StructField("account_id", T.IntegerType()),
    T.StructField("hero_id", T.IntegerType()),
    T.StructField("team_number", T.IntegerType()),
    T.StructField("kills", T.IntegerType()),
    T.StructField("deaths", T.IntegerType()),
    T.StructField("assists", T.IntegerType()),
    T.StructField("gold", T.IntegerType()),
    T.StructField("gold_spent", T.IntegerType()),
    T.StructField("net_worth", T.IntegerType()),
    T.StructField("gold_per_min", T.IntegerType()),
    T.StructField("xp_per_min", T.IntegerType()),
    T.StructField("hero_damage", T.IntegerType()),
    T.StructField("hero_healing", T.IntegerType()),
    T.StructField("tower_damage", T.IntegerType()),
    T.StructField("tower_kills", T.IntegerType()),
    T.StructField("stuns", T.DoubleType()),
    T.StructField("last_hits", T.IntegerType()),
    T.StructField("denies", T.IntegerType()),
    T.StructField("camps_stacked", T.IntegerType()),
    T.StructField("creeps_stacked", T.IntegerType()),
    T.StructField("neutral_kills", T.IntegerType()),
    T.StructField("rune_pickups", T.IntegerType()),
    T.StructField("obs_log", T.ArrayType(T.StructType([T.StructField("time", T.DoubleType())]))),
    T.StructField("sen_log", T.ArrayType(T.StructType([T.StructField("time", T.DoubleType())]))),
    T.StructField("obs_placed", T.IntegerType()),
    T.StructField("sen_placed", T.IntegerType()),
    T.StructField("observer_kills", T.IntegerType()),
    T.StructField("sentry_kills", T.IntegerType()),
    T.StructField("purchase_ward_observer", T.IntegerType()),
    T.StructField("purchase_ward_sentry", T.IntegerType()),
    T.StructField("personaname", T.StringType()),
    T.StructField("level", T.IntegerType()),
    T.StructField("item_0", T.IntegerType()),
    T.StructField("item_1", T.IntegerType()),
    T.StructField("item_2", T.IntegerType()),
    T.StructField("item_3", T.IntegerType()),
    T.StructField("item_4", T.IntegerType()),
    T.StructField("item_5", T.IntegerType()),
    T.StructField("item_neutral", T.IntegerType()),
    T.StructField("backpack_0", T.IntegerType()),
    T.StructField("backpack_1", T.IntegerType()),
    T.StructField("backpack_2", T.IntegerType()),
    T.StructField("backpack_3", T.IntegerType()),
    T.StructField("leaver_status", T.IntegerType()),
    T.StructField("randomed", T.BooleanType()),
    T.StructField("firstblood_claimed", T.IntegerType()),
    T.StructField("buyback_count", T.IntegerType()),
])

PICKS_BANS_SCHEMA = T.ArrayType(T.StructType([
    T.StructField("order", T.IntegerType()),
    T.StructField("hero_id", T.IntegerType()),
    T.StructField("is_pick", T.BooleanType()),
    T.StructField("team", T.IntegerType()),
    T.StructField("player_slot", T.IntegerType()),
]))

HERO_RECORD_SCHEMA = T.StructType([
    T.StructField("name", T.StringType()),
    T.StructField("localized_name", T.StringType()),
    T.StructField("primary_attr", T.StringType()),
    T.StructField("attack_type", T.StringType()),
    T.StructField("roles", T.ArrayType(T.StringType())),
    T.StructField("img", T.StringType()),
])
